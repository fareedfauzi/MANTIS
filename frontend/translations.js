let METIS_LANG = localStorage.getItem('metis_lang') || 'vi';

function t(key) {
  if (METIS_LANG === 'vi' && METIS_TRANSLATIONS.vi[key]) {
    return METIS_TRANSLATIONS.vi[key];
  }
  return key;
}

function applyTranslations() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const translation = t(key);
    if (translation) el.textContent = translation;
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    const translation = t(key);
    if (translation) el.setAttribute('placeholder', translation);
  });
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const key = el.getAttribute('data-i18n-title');
    const translation = t(key);
    if (translation) el.setAttribute('title', translation);
  });
}

function setLang(lang) {
  METIS_LANG = lang;
  localStorage.setItem('metis_lang', lang);
  applyTranslations();
  const btn = document.getElementById('metis-lang-toggle');
  if (btn) btn.textContent = lang === 'vi' ? '🇻🇳 Tiếng Việt' : '🇬🇧 English';
}

document.addEventListener('DOMContentLoaded', () => {
  applyTranslations();
});
