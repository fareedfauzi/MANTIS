def load_tombstones() -> set:
    """Load deleted rule paths/IDs so deleted rules are never recreated or synced back."""
    if not TOMBSTONE_FILE.exists():
        return set()
    try:
        with open(TOMBSTONE_FILE, "r", encoding="utf-8") as f:
            data = json.load(f)
            return set(data) if isinstance(data, list) else set()
    except Exception as e:
        logger.error(f"Error loading tombstones: {e}")
        return set()


def add_tombstone(rule_identifier: str):
    """Add a rule identifier (filename or relative path) to the tombstone list."""
    tombstones = load_tombstones()
    tombstones.add(rule_identifier)
    try:
        with open(TOMBSTONE_FILE, "w", encoding="utf-8") as f:
            json.dump(sorted(list(tombstones)), f, indent=2)
    except Exception as e:
        logger.error(f"Error saving tombstone {rule_identifier}: {e}")


def seed_all_repositories(overwrite: bool = False):
    """Seeds rich curated Sigma rules into all repository directories."""
    tombstones = load_tombstones()
    results = {}

    for repo_id, rules in SEED_RULES.items():
        repo_dir = SIGMA_DATA_DIR / repo_id
        repo_dir.mkdir(parents=True, exist_ok=True)
        count = 0

        for item in rules:
            fname = item["filename"]
            rel_path = f"{repo_id}/{fname}"

            # If rule has been marked as deleted by the user, do not recreate!
            if fname in tombstones or rel_path in tombstones:
                continue

            file_path = repo_dir / fname
            if not file_path.exists() or overwrite:
                with open(file_path, "w", encoding="utf-8") as f:
                    f.write(item["content"].strip() + "\n")
                count += 1

        results[repo_id] = count

    return results


def is_repo_downloaded(repo_id: str) -> bool:
    """Check if repository already has its full rule set downloaded."""
    if repo_id == "custom":
        return True
    target_dir = SIGMA_DATA_DIR / repo_id
    if not target_dir.exists():
        return False
    # If it has more than 20 rules, it is considered downloaded (seed has only 5-10)
    count = sum(1 for p in target_dir.rglob("*") if p.is_file() and p.suffix.lower() in (".yml", ".yaml"))
    return count >= 20


def sync_repository(repo_id: str, progress_key: str = None) -> dict:
    """
    Downloads/syncs upstream repository rules from GitHub with live byte and extraction progress.
    Extracts all valid detection rules preserving directory categories.
    Respects deleted rules tombstone list (sigma_deleted_rules.json).
    """
    if repo_id not in REPOSITORIES:
        return {"success": False, "error": f"Unknown repository: {repo_id}"}

    repo_info = REPOSITORIES[repo_id]
    zip_url = repo_info.get("zip_url")
    if not zip_url:
        return {"success": True, "repo": repo_id, "imported": 0, "message": "Local repository, no upstream URL"}

    pkey = progress_key or repo_info.get("progress_key", f"sigma-{repo_id}")
    target_dir = SIGMA_DATA_DIR / repo_id
    target_dir.mkdir(parents=True, exist_ok=True)
    DOWNLOADS_DIR.mkdir(parents=True, exist_ok=True)
    zip_file = DOWNLOADS_DIR / f"{repo_id}.zip"

    tombstones = load_tombstones()

    if progress:
        progress.start(pkey, total=None, message=f"Connecting to {repo_info['name']}")

    try:
        # Stream download archive in 256 KiB chunks
        req = urllib.request.Request(
            zip_url,
            headers={"User-Agent": "MANTIS-Sigma-Collector/2.0"}
        )
        with urllib.request.urlopen(req, timeout=90) as resp, open(zip_file, "wb") as out_f:
            length = resp.headers.get("Content-Length")
            total = int(length) if length and length.isdigit() else None
            if progress:
                progress.set_total(pkey, total)
                progress.advance(pkey, 0, f"Downloading {repo_info['name']}")

            done = 0
            while True:
                chunk = resp.read(256 * 1024)
                if not chunk:
                    break
                out_f.write(chunk)
                done += len(chunk)
                if progress:
                    progress.set_bytes(pkey, done, total)

        if progress:
            progress.advance(pkey, 0, f"Extracting {repo_info['name']} rules")

        allowed_prefixes = repo_info.get("allowed_prefixes", [])
        strip_prefix = repo_info.get("strip_prefix", "")
        imported_count = 0

        with zipfile.ZipFile(zip_file, "r") as z:
            for zip_info in z.infolist():
                if zip_info.is_dir():
                    continue
                name = zip_info.filename
                if not (name.endswith(".yml") or name.endswith(".yaml")):
                    continue

                # Skip non-rule files (.github, workflows, tests, regression, doc, etc.)
                if any(x in name.lower() for x in ("/.github/", "/tests/", "/test/", "/regression_data/", "/doc/", "/scripts/", "/config/data_mapping/")):
                    continue

                # Check allowed prefixes
                if allowed_prefixes:
                    if not any(name.startswith(pfx) for pfx in allowed_prefixes):
                        continue

                # Compute clean relative path
                if strip_prefix and name.startswith(strip_prefix):
                    rel_name = name[len(strip_prefix):].lstrip("/")
                else:
                    parts = name.split("/", 1)
                    rel_name = parts[1] if len(parts) > 1 else parts[0]

                subpath = repo_info.get("subpath") or ""
                if subpath:
                    if not rel_name.startswith(subpath + "/"):
                        continue
                    rel_name = rel_name[len(subpath):].lstrip("/")

                base_name = os.path.basename(rel_name)
                rel_path = f"{repo_id}/{rel_name}"

                # Do not sync deleted / tombstoned files!
                if base_name in tombstones or rel_name in tombstones or rel_path in tombstones:
                    continue

                content = z.read(zip_info).decode("utf-8", errors="ignore")
                # Basic check that it is a Sigma rule
                if "title:" in content and ("detection:" in content or "logsource:" in content):
                    dest_file = target_dir / rel_name
                    dest_file.parent.mkdir(parents=True, exist_ok=True)
                    with open(dest_file, "w", encoding="utf-8") as f:
                        f.write(content)
                    imported_count += 1

        # Clean up zip file to save disk space
        try:
            zip_file.unlink(missing_ok=True)
        except Exception:
            pass

        msg = f"Successfully synced {imported_count:,} rules from {repo_info['name']}"
        logger.info(msg)
        if progress:
            progress.finish(pkey, f"{imported_count:,} rules ready")

        return {
            "success": True,
            "repo": repo_id,
            "imported": imported_count,
            "message": msg
        }

    except Exception as e:
        logger.warning(f"Live sync for {repo_id} failed: {e}. Falling back to curated seed.")
        if progress:
            progress.fail(pkey, f"Sync error: {e}")
        seed_res = seed_all_repositories(overwrite=False)
        return {
            "success": False,
            "repo": repo_id,
            "error": str(e),
            "fallback_seeded": seed_res.get(repo_id, 0),
            "message": f"Could not reach remote repo ({e}), loaded offline seed rules."
        }


def download_all_repositories(force: bool = False) -> dict:
    """Download and collect all rules from all 6 external upstream repositories."""
    results = {}
    for repo_id in [rid for rid, m in list(REPOSITORIES.items()) if m.get("zip_url")]:
        pkey = REPOSITORIES[repo_id].get("progress_key", f"sigma-{repo_id}")
        if not force and is_repo_downloaded(repo_id):
            if progress:
                progress.skip(pkey, "Already up to date (cached)")
            results[repo_id] = {"status": "skipped", "message": "Already up to date"}
            continue

        res = sync_repository(repo_id, progress_key=pkey)
        results[repo_id] = res

    # Force re-indexing in sigma_repos if available
    try:
        import sigma_repos
        sigma_repos.index_rules(force=True)
    except Exception as err:
        logger.debug("Reindexing after download: %s", err)

    return results


