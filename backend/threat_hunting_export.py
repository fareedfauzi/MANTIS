"""
MANTIS AI Threat Hunting Export Engine
Generates:
1. Individual Query Exports: Plain Text, JSON, Markdown
2. Complete Hunting Packages:
   - Comprehensive Markdown Threat Hunting Playbook
   - CSV Query Inventory (ready for SOC ingestion or tracking)
   - ZIP Archive containing organized platform directories, CSV manifest, and Playbook
"""

from __future__ import annotations

import csv
import io
import json
import re
from typing import Any, Dict, List, Optional, Tuple
import zipfile


def export_single_query(query: Dict[str, Any], format_type: str = "txt") -> Tuple[str, str, str]:
    """
    Exports an individual hunting query.
    Returns: (content_str_or_bytes, media_type, filename)
    """
    fmt = format_type.lower().strip()
    title = query.get("title", "Threat_Hunting_Query").replace(" ", "_")
    platform = query.get("platform", "query")

    if fmt == "json":
        data = {
            "title": query.get("title"),
            "platform": query.get("platform"),
            "language": query.get("query_language"),
            "mode": query.get("mode"),
            "query": query.get("query_text"),
            "explanation": query.get("explanation"),
            "telemetry_schema": query.get("telemetry_schema"),
            "validation_status": query.get("validation_status"),
            "tuning_guidance": query.get("tuning_guidance"),
            "created_at": query.get("created_at")
        }
        return json.dumps(data, indent=2), "application/json", f"{title}.json"

    elif fmt in ("md", "markdown"):
        md = f"""# {query.get('title')}

- **Platform:** {query.get('platform', '').upper()}
- **Language:** {query.get('query_language')}
- **Mode:** {query.get('mode', '').title()}
- **Validation Status:** `{query.get('validation_status')}`

## Hunting Query

```{query.get('platform', 'sql')}
{query.get('query_text')}
```

## Logic & Explanation
{query.get('explanation', 'N/A')}

## Tuning & False Positive Guidance
{query.get('tuning_guidance', 'Review baseline activity.')}
"""
        return md, "text/markdown", f"{title}.md"

    else:
        # Default plain text
        ext = "spl" if platform == "splunk" else ("kql" if "kql" in str(query.get("query_language", "")).lower() else "txt")
        return query.get("query_text", ""), "text/plain", f"{title}.{ext}"


def export_playbook_markdown(investigation: Dict[str, Any]) -> str:
    """Generates an end-to-end Markdown Threat Hunting Playbook from an investigation."""
    title = investigation.get("title", "Threat Hunting Investigation")
    summary = investigation.get("summary", "Technical findings and hunting hypotheses.")
    findings = investigation.get("findings", [])
    hypotheses = investigation.get("hypotheses", [])
    queries = investigation.get("queries", [])

    lines = [
        f"# Threat Hunting Playbook: {title}",
        "",
        f"**Generated by MANTIS AI Threat Hunting Studio**",
        f"- Source Type: {investigation.get('source_type', 'Manual')}",
        f"- Target Queries Generated: {len(queries)}",
        "",
        "## Executive Summary",
        summary,
        "",
        "## Extracted Technical Findings & Observable Behaviors",
        ""
    ]

    for i, f in enumerate(findings, 1):
        lines.extend([
            f"### {i}. {f.get('title')}",
            f"- **Tactic / Technique:** {f.get('attack_tactic')} - {f.get('attack_technique')} ({f.get('attack_id')})",
            f"- **Confidence:** `{f.get('confidence')}`",
            f"- **Description:** {f.get('description')}",
            f"- **Evidence Reference:** *\"{f.get('evidence_quote')}\"*",
            f"- **Key Artifacts:** {', '.join(f.get('artifacts') or [])}",
            ""
        ])

    lines.extend([
        "## Threat Hunting Hypotheses",
        ""
    ])

    for i, h in enumerate(hypotheses, 1):
        lines.extend([
            f"### Hypothesis {i}: {h.get('title')}",
            h.get("description", ""),
            "",
            f"- **Required Telemetry:** {h.get('telemetry_required')}",
            f"- **Event IDs:** {h.get('event_ids')}",
            f"- **Hunting Strategy:** {h.get('hunting_strategy')}",
            f"- **Potential False Positives:** {h.get('potential_false_positives')}",
            f"- **Investigation Pivots:** {h.get('investigation_pivots')}",
            ""
        ])

    lines.extend([
        "## Platform-Specific Hunting & Detection Queries",
        ""
    ])

    for q in queries:
        lines.extend([
            f"### {q.get('title')} ({q.get('platform', '').upper()} - {q.get('query_language')})",
            f"- **Mode:** `{q.get('mode')}` | **Status:** `{q.get('validation_status')}`",
            "",
            f"```{q.get('platform', 'text')}",
            q.get("query_text", ""),
            "```",
            "",
            f"**Logic Explanation:** {q.get('explanation')}",
            "",
            f"**Tuning Guidance:** {q.get('tuning_guidance')}",
            "",
            "---",
            ""
        ])

    return "\n".join(lines)


def export_inventory_csv(queries: List[Dict[str, Any]]) -> str:
    """Generates a CSV query inventory spreadsheet."""
    output = io.StringIO()
    writer = csv.writer(output)
    writer.writerow([
        "Query Title", "Platform", "Query Language", "Mode",
        "Query Text", "Validation Status", "Explanation", "Tuning Guidance"
    ])

    for q in queries:
        writer.writerow([
            q.get("title", ""),
            q.get("platform", ""),
            q.get("query_language", ""),
            q.get("mode", ""),
            q.get("query_text", ""),
            q.get("validation_status", ""),
            q.get("explanation", ""),
            q.get("tuning_guidance", "")
        ])

    return output.getvalue()


def export_hunting_package_zip(investigation: Dict[str, Any]) -> bytes:
    """
    Creates a ZIP archive containing:
    - PLAYBOOK.md
    - INVENTORY.csv
    - INVESTIGATION.json
    - Subdirectories per platform containing individual query files
    """
    zip_buffer = io.BytesIO()

    with zipfile.ZipFile(zip_buffer, "w", zipfile.ZIP_DEFLATED) as zf:
        # 1. Playbook
        playbook_md = export_playbook_markdown(investigation)
        zf.writestr("PLAYBOOK.md", playbook_md)

        # 2. CSV Inventory
        csv_data = export_inventory_csv(investigation.get("queries", []))
        zf.writestr("INVENTORY.csv", csv_data)

        # 3. Full JSON representation
        zf.writestr("INVESTIGATION.json", json.dumps(investigation, indent=2))

        # 4. Organized platform folders
        for q in investigation.get("queries", []):
            plat = (q.get("platform") or "other").lower()
            q_title = re.sub(r"[^\w\-_\.]", "_", q.get("title", "query"))[:60]
            ext = "spl" if plat == "splunk" else ("kql" if "kql" in str(q.get("query_language", "")).lower() else "txt")
            folder_name = plat.capitalize()

            content, _, _ = export_single_query(q, "txt")
            zf.writestr(f"Queries/{folder_name}/{q_title}.{ext}", content)

    zip_buffer.seek(0)
    return zip_buffer.getvalue()
